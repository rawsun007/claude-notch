"""Make ClaudeNotch's own sound effects, named after the Mac's picker.

The macOS app offers the system sounds Funk, Pop, Tink, Glass, Submarine,
Hero, Blow, Bottle, Frog, Morse, Ping, Purr and Sosumi. Apple's recordings
are not ours to ship, so these are original sounds synthesised here to
play the same part: a short pop, a light metallic tick, a glass bell, a
sonar ping, and so on. Pure Python (wave + math); deterministic, so the
files in windows/resources/sounds can be regenerated byte for byte:

    python windows/tools/make_sounds.py
"""

from __future__ import annotations

import math
import os
import random
import struct
import wave

RATE = 44100
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "resources", "sounds")


def env(t: float, attack: float, decay: float) -> float:
    if t < attack:
        return t / attack
    return math.exp(-(t - attack) / decay)


def tone(dur, parts, attack=0.003, decay=0.15, sweep=None):
    """Sum of (freq multiple, amplitude) partials over a base frequency that
    may sweep: sweep = (f0, f1)."""
    n = int(dur * RATE)
    f0, f1 = sweep
    out, phase = [], [0.0] * len(parts)
    for i in range(n):
        t = i / RATE
        f = f0 * (f1 / f0) ** (t / dur)
        s = 0.0
        for k, (mult, amp) in enumerate(parts):
            phase[k] += 2 * math.pi * f * mult / RATE
            s += amp * math.sin(phase[k])
        out.append(s * env(t, attack, decay))
    return out


def silence(dur):
    return [0.0] * int(dur * RATE)


def mix(*tracks):
    n = max(len(t) for t in tracks)
    return [sum(t[i] for t in tracks if i < len(t)) for i in range(n)]


def noise(dur, decay, colour=0.9, seed=1):
    rng = random.Random(seed)
    out, last = [], 0.0
    for i in range(int(dur * RATE)):
        last = colour * last + (1 - colour) * rng.uniform(-1, 1)
        t = i / RATE
        out.append(last * 4 * env(t, 0.02, decay))
    return out


def save(name: str, samples) -> None:
    peak = max(1e-9, max(abs(s) for s in samples))
    gain = 0.8 / peak
    fade = int(0.004 * RATE)
    data = bytearray()
    for i, s in enumerate(samples):
        if i > len(samples) - fade:
            s *= (len(samples) - i) / fade
        data += struct.pack("<h", int(max(-1, min(1, s * gain)) * 32767))
    os.makedirs(OUT, exist_ok=True)
    with wave.open(os.path.join(OUT, name + ".wav"), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(RATE)
        w.writeframes(bytes(data))


def make() -> list[str]:
    sounds = {
        # A soft, quick pop: a falling blip.
        "Pop": tone(0.12, [(1, 1), (2, 0.25)], decay=0.035, sweep=(900, 320)),
        # A light metallic tick.
        "Tink": tone(0.28, [(1, 1), (1.51, 0.5), (2.76, 0.25)], decay=0.06, sweep=(2900, 2900)),
        # A glass bell, ringing on.
        "Glass": tone(1.3, [(1, 1), (2.76, 0.45), (5.4, 0.2), (8.93, 0.08)], decay=0.45, sweep=(1568, 1568)),
        # A low, round "bwomp" for something that wants you.
        "Funk": mix(tone(0.16, [(1, 1), (2, 0.5), (3, 0.3)], decay=0.08, sweep=(330, 250)),
                    silence(0.11) + tone(0.24, [(1, 1), (2, 0.5), (3, 0.3)], decay=0.1, sweep=(250, 190))),
        # A sonar ping with a long tail.
        "Submarine": tone(1.4, [(1, 1), (2, 0.12)], attack=0.01, decay=0.5, sweep=(620, 600)),
        # A rising fanfare of four chimes.
        "Hero": mix(*[silence(0.09 * k) + tone(0.9 - 0.09 * k, [(1, 1), (2, 0.3), (3, 0.1)], decay=0.3,
                                                   sweep=(f, f))
                      for k, f in enumerate((523.25, 659.25, 783.99, 1046.5))]),
        # A breath of air.
        "Blow": noise(0.7, 0.25, colour=0.97, seed=3),
        # A hollow knock, like a bottle.
        "Bottle": mix(tone(0.45, [(1, 1), (2.1, 0.3)], attack=0.01, decay=0.12, sweep=(430, 400)),
                      noise(0.08, 0.02, colour=0.6, seed=5)),
        # Two quick croaks.
        "Frog": mix(tone(0.11, [(1, 1), (3, 0.6), (5, 0.3)], decay=0.05, sweep=(260, 180)),
                    silence(0.15) + tone(0.13, [(1, 1), (3, 0.6), (5, 0.3)], decay=0.06, sweep=(280, 170))),
        # Three short beeps.
        "Morse": mix(*[silence(0.12 * k) + tone(0.07, [(1, 1)], attack=0.004, decay=0.5, sweep=(880, 880))
                       for k in range(3)]),
        # A clear, single ping.
        "Ping": tone(0.9, [(1, 1), (2.4, 0.2)], decay=0.3, sweep=(1320, 1320)),
        # A low purr.
        "Purr": [s * (0.6 + 0.4 * math.sin(2 * math.pi * 28 * i / RATE))
                 for i, s in enumerate(tone(0.6, [(1, 1), (2, 0.6), (3, 0.3)], attack=0.04, decay=0.3,
                                            sweep=(118, 110)))],
        # Two bright xylophone notes.
        "Sosumi": mix(tone(0.4, [(1, 1), (3.9, 0.3)], decay=0.12, sweep=(988, 988)),
                      silence(0.14) + tone(0.45, [(1, 1), (3.9, 0.3)], decay=0.14, sweep=(1319, 1319))),
    }
    for name, samples in sounds.items():
        save(name, samples)
    return sorted(sounds)


if __name__ == "__main__":
    print("made", ", ".join(make()))
